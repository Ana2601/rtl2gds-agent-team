"""RTL agent's code generator for the dot-product design family.

The expert RTL agent does not write free-form code: it picks an architecture
from a small, verified design space and this generator renders it. (In
`--policy claude` mode the RTL agent writes the module itself, under the same
lint + verification gates.)

Architecture knobs:
    latency     1..4   cycles from input registers' capture to y (spec allows 1..4)
    cut         where the extra pipeline registers go, in order of preference:
                "products" (after the multipliers), "partials" (after the first
                adder level), "booth" (inside the multiplier: partial-product rows)
"""
from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Arch:
    latency: int = 1
    cuts: tuple = ()            # subset of ("products", "partials", "mult_mid")

    def describe(self) -> str:
        return f"latency {self.latency}, pipeline registers after: {', '.join(self.cuts) or 'none'}"


def render(arch: Arch, name: str = "dot4") -> str:
    assert 1 <= arch.latency <= 4 and len(arch.cuts) == arch.latency - 1, arch
    c = set(arch.cuts)
    L = []
    L.append(f"// {name}: 4-lane signed 8-bit dot product. Generated by the RTL agent.")
    L.append(f"// Architecture: {arch.describe()}.")
    L.append(f"module {name} (")
    L.append("    input  logic               clk,")
    L.append("    input  logic               rst_n,")
    L.append("    input  logic               in_valid,")
    L.append("    input  logic        [31:0] a,")
    L.append("    input  logic        [31:0] b,")
    L.append("    output logic               out_valid,")
    L.append("    output logic signed [17:0] y")
    L.append(");")
    L.append(f"    localparam int LAT = {arch.latency};")
    L.append("")
    L.append("    // input registers")
    L.append("    logic signed [7:0] ar [4], br [4];")
    L.append("    always_ff @(posedge clk)")
    L.append("        if (in_valid)")
    L.append("            for (int k = 0; k < 4; k++) begin")
    L.append("                ar[k] <= a[8*k +: 8];")
    L.append("                br[k] <= b[8*k +: 8];")
    L.append("            end")
    L.append("")
    # multipliers, optionally split into two halves of partial products
    if "mult_mid" in c:
        L.append("    // multipliers split in two: low and high nibble of b, registered in between")
        L.append("    logic signed [15:0] plo_d [4], phi_d [4];")
        L.append("    logic signed [15:0] plo [4], phi [4];")
        L.append("    always_comb")
        L.append("        for (int k = 0; k < 4; k++) begin")
        L.append("            plo_d[k] = 16'(ar[k]) * $signed({1'b0, br[k][3:0]});")
        L.append("            phi_d[k] = 16'(ar[k]) * 16'($signed(br[k][7:4]));")
        L.append("        end")
        L.append("    always_ff @(posedge clk)")
        L.append("        for (int k = 0; k < 4; k++) begin")
        L.append("            plo[k] <= plo_d[k];")
        L.append("            phi[k] <= phi_d[k];")
        L.append("        end")
        L.append("    logic signed [15:0] p [4];")
        L.append("    always_comb for (int k = 0; k < 4; k++) p[k] = plo[k] + (phi[k] <<< 4);")
    else:
        L.append("    logic signed [15:0] p [4];")
        L.append("    always_comb for (int k = 0; k < 4; k++) p[k] = 16'(ar[k]) * 16'(br[k]);")
    src = "p"
    if "products" in c:
        L.append("")
        L.append("    // pipeline register after the multipliers")
        L.append("    logic signed [15:0] pq [4];")
        L.append("    always_ff @(posedge clk) for (int k = 0; k < 4; k++) pq[k] <= p[k];")
        src = "pq"
    L.append("")
    L.append("    // balanced adder tree")
    L.append("    logic signed [16:0] s01, s23;")
    L.append(f"    assign s01 = 17'({src}[0]) + 17'({src}[1]);")
    L.append(f"    assign s23 = 17'({src}[2]) + 17'({src}[3]);")
    a01, a23 = "s01", "s23"
    if "partials" in c:
        L.append("    logic signed [16:0] s01q, s23q;")
        L.append("    always_ff @(posedge clk) begin")
        L.append("        s01q <= s01;")
        L.append("        s23q <= s23;")
        L.append("    end")
        a01, a23 = "s01q", "s23q"
    L.append("")
    L.append("    // output register")
    L.append("    always_ff @(posedge clk)")
    L.append(f"        y <= 18'({a01}) + 18'({a23});")
    L.append("")
    L.append("    // valid pipeline: the only state that needs a reset")
    L.append("    logic [LAT:0] v;")
    L.append("    always_ff @(posedge clk or negedge rst_n)")
    L.append("        if (!rst_n) v <= '0;")
    L.append("        else        v <= {v[LAT-1:0], in_valid};")
    L.append("    assign out_valid = v[LAT];")
    L.append("endmodule")
    return "\n".join(L) + "\n"


# The order in which the expert RTL agent adds pipeline cuts (cheapest first)
CUT_ORDER = ("products", "partials", "mult_mid")


# Which cut splits a critical path, by the register it ends at
_SPLITS = {"y": ("products", "partials", "mult_mid"),        # path ends at the output register
           "pq": ("mult_mid",),                               # ... at the product register: the multiplier itself
           "plo": ("products",), "phi": ("products",),         # ... at the split partial products
           "s01q": ("products", "mult_mid"), "s23q": ("products", "mult_mid")}


def deeper(arch: Arch, endpoint: str | None = None) -> Arch | None:
    """One more pipeline stage, placed to split the critical path that ends at
    `endpoint` (an ORFS register name such as 'pq[0][15]$_DFF_P_'), or None if the
    spec's latency budget is used up or no cut can split that path."""
    if arch.latency >= 4:
        return None
    reg = (endpoint or "y").split("[")[0]
    prefs = _SPLITS.get(reg, CUT_ORDER)
    nxt = next((c for c in prefs if c not in arch.cuts), None)
    if nxt is None:
        return None
    return Arch(arch.latency + 1, tuple(sorted(arch.cuts + (nxt,), key=CUT_ORDER.index)))
